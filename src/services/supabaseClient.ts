import { createClient } from '@supabase/supabase-js';
import { getStoredSettings } from '../utils/storage';

export const DEFAULT_SUPABASE_PROJECT_ID = 'qmkhqxgmfjuidgxqcznw';
export const DEFAULT_SUPABASE_URL = 'https://qmkhqxgmfjuidgxqcznw.supabase.co';
export const DEFAULT_SUPABASE_ANON_KEY = 'sb_publishable_Zq3Q0ppOizmxF_mVJVfNgw_mnJynokf';

export function getSupabaseConfig() {
  const settings = getStoredSettings();
  const url = (settings.supabaseUrl || DEFAULT_SUPABASE_URL).trim();
  const anonKey = (settings.supabaseAnonKey || DEFAULT_SUPABASE_ANON_KEY).trim();
  const projectId = (settings.supabaseProjectId || DEFAULT_SUPABASE_PROJECT_ID).trim();

  return {
    url,
    anonKey,
    projectId,
  };
}

export function createSupabaseInstance() {
  const config = getSupabaseConfig();
  return createClient(config.url, config.anonKey, {
    auth: {
      persistSession: false,
      autoRefreshToken: false,
    },
  });
}

