/**
 * SQL Schema definition to easily run in Supabase SQL Editor.
 * Creates bills and bill_items tables with duplicate protection,
 * helpful indexes, and Row Level Security policies.
 */
export const SUPABASE_SCHEMA_SQL = `-- ====================================================================
-- TULJAI PHATAKA BILLING DATABASE SCHEMA FOR SUPABASE
-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- Safe to re-run multiple times (prevents 42710 policy already exists errors)
-- ====================================================================

-- 1. Drop existing empty tables and cascade dependencies safely
DROP TABLE IF EXISTS public.bill_items CASCADE;
DROP TABLE IF EXISTS public.bills CASCADE;

-- 2. Create bills table
CREATE TABLE public.bills (
    id TEXT PRIMARY KEY,
    bill_no TEXT UNIQUE NOT NULL,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    timestamp BIGINT,
    customer_name TEXT DEFAULT 'Walk-in Customer',
    customer_phone TEXT,
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0,
    discount_percent NUMERIC(5, 2) DEFAULT 0,
    discount_amount NUMERIC(12, 2) DEFAULT 0,
    tax_percent NUMERIC(5, 2) DEFAULT 0,
    tax_amount NUMERIC(12, 2) DEFAULT 0,
    grand_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    billed_by TEXT DEFAULT 'Shop Admin',
    items_summary TEXT,
    items_count INTEGER DEFAULT 0,
    sync_status TEXT DEFAULT 'Synced',
    synced_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create bill_items table
CREATE TABLE public.bill_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_no TEXT NOT NULL REFERENCES public.bills(bill_no) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category TEXT,
    qty INTEGER NOT NULL DEFAULT 1,
    unit_price NUMERIC(12, 2) NOT NULL DEFAULT 0,
    line_total NUMERIC(12, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Helpful search and lookup indexes
CREATE INDEX IF NOT EXISTS idx_bills_bill_no ON public.bills (bill_no);
CREATE INDEX IF NOT EXISTS idx_bills_date ON public.bills (date);
CREATE INDEX IF NOT EXISTS idx_bill_items_bill_no ON public.bill_items (bill_no);

-- 5. Enable Row Level Security (RLS)
ALTER TABLE public.bills ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bill_items ENABLE ROW LEVEL SECURITY;

-- 6. Clean up any existing policies (Prevents ERROR 42710)
DROP POLICY IF EXISTS "Allow anon all on bills" ON public.bills;
DROP POLICY IF EXISTS "Allow anon all on bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public read on bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public insert on bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public update on bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public delete on bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public read bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public insert bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public update bills" ON public.bills;
DROP POLICY IF EXISTS "Allow public delete bills" ON public.bills;

DROP POLICY IF EXISTS "Allow public read on bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public insert on bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public update on bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public delete on bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public read bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public insert bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public update bill_items" ON public.bill_items;
DROP POLICY IF EXISTS "Allow public delete bill_items" ON public.bill_items;

-- 7. Create permissive policies for Point-of-Sale applet
CREATE POLICY "Allow anon all on bills" ON public.bills
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Allow anon all on bill_items" ON public.bill_items
    FOR ALL
    TO anon, authenticated
    USING (true)
    WITH CHECK (true);
`;
